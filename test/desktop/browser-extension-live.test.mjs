import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { chromium } from 'playwright';
import { CompanionCapture } from '../../desktop/electron/companion-capture.mjs';
import { McpManager } from '../../src/integrations/mcp-manager.mjs';
import { ExtensionBrowserAdapter } from '../../tools/browser/extension.mjs';
import { BROWSER_EXTENSION_MCP_ID } from '../../desktop/browser-helper/control-protocol.mjs';

test('real companion pairs once, submits a form through MCP and reconnects after both process restarts', { timeout: 150_000 }, async t => {
  const root = await mkdtemp(join(tmpdir(), 'ankita-extension-live-')), profile = join(root, 'profile');
  const extension = resolve('desktop/browser-helper');
  let posts = 0, service, context;
  const server = http.createServer((req, res) => {
    if (req.url === '/posted') { posts++; res.end('Saved'); return; }
    res.setHeader('Content-Type', 'text/html');
    res.end('<!doctype html><title>Live extension fixture</title><form><label>Post<textarea name="post"></textarea></label><button>Publish</button><output></output></form><script>document.querySelector("form").onsubmit=async e=>{e.preventDefault();await fetch("/posted",{method:"POST"});document.querySelector("output").textContent=document.querySelector("textarea").value}</script>');
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const options = { configFile: join(root, 'bridge.json'), threadExists: () => true, onCapture() {} };
  const mcp = new McpManager();
  t.after(async () => { await context?.close(); await mcp.closeAll(); await service?.close(); await new Promise(resolve => server.close(resolve)); await rm(root, { recursive: true, force: true }); });
  const launch = () => chromium.launchPersistentContext(profile, { channel: 'chromium', headless: true, args: [`--disable-extensions-except=${extension}`, `--load-extension=${extension}`] });
  service = await new CompanionCapture(options).start();
  context = await launch();
  const worker = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
  const id = new URL(worker.url()).host;
  const popup = await context.newPage(); await popup.goto(`chrome-extension://${id}/popup.html`);
  await popup.getByRole('textbox', { name: 'ANKITA pairing code' }).fill(JSON.stringify(service.setup({ control: true })));
  await popup.getByRole('button', { name: 'Pair with ANKITA', exact: true }).click();
  await popup.getByText('Connected to Ankita', { exact: true }).waitFor();
  const firstPair = await worker.evaluate(() => chrome.storage.local.get('pairedDesktop'));
  const address = service.address;
  const ensureConnected = async () => {
    if (!mcp.has(BROWSER_EXTENSION_MCP_ID)) await mcp.connect({ id: BROWSER_EXTENSION_MCP_ID, transport: 'http', url: (await service.browserGateway()).url, hidden: true });
  };
  const adapter = new ExtensionBrowserAdapter(mcp, { ensureConnected, ownedTabs: true });
  const ctx = { cwd: root, settings: {}, config: { allowPrivateHosts: true } };
  const check = async args => { const result = await adapter.execute(args, ctx); assert.equal(result.error, null, result.error?.message); return result; };
  const waitConnected = async () => { const deadline = Date.now() + 40_000; while (!service.browserStatus().connected && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 100)); assert.equal(service.browserStatus().connected, true); };
  const opened = await check({ action: 'open', url: `http://127.0.0.1:${server.address().port}/` });
  const postRef = opened.observation.controls.find(c => c.name === 'Post').ref;
  const filled = await check({ action: 'act', op: 'fill', ref: postRef, text: 'Written through the real browser companion' });
  await check({ action: 'act', op: 'click', ref: filled.observation.controls.find(c => c.name === 'Publish').ref });
  const formPage = context.pages().find(page => page.url().startsWith(`http://127.0.0.1:${server.address().port}`));
  await formPage.getByText('Written through the real browser companion', { exact: true }).waitFor();
  assert.equal(posts, 1);
  const fresh = await check({ action: 'snapshot' });
  await check({ action: 'act', op: 'press', ref: fresh.observation.controls.find(c => c.name === 'Publish').ref, text: 'Enter' });
  await formPage.waitForFunction(() => document.querySelector('output').textContent.length > 0);
  assert.equal(posts, 2, 'native Enter submits exactly once');
  const screenshot = await check({ action: 'screenshot' });
  assert.ok(screenshot.artifacts[0].bytes > 0);
  const cdp = await context.browser().newBrowserCDPSession();
  const { targetInfos } = await cdp.send('Target.getTargets');
  const workerTarget = targetInfos.find(target => target.type === 'service_worker' && target.url === worker.url());
  assert.ok(workerTarget);
  await cdp.send('Target.closeTarget', { targetId: workerTarget.targetId });
  await popup.reload(); await popup.getByText('Connected to Ankita', { exact: true }).waitFor(); await waitConnected();
  await check({ action: 'snapshot' });
  assert.equal(posts, 2, 'worker restart preserves tab ownership without replay');
  await mcp.disconnect(BROWSER_EXTENSION_MCP_ID); await service.close();
  service = await new CompanionCapture(options).start();
  assert.equal(service.address, address);
  await popup.getByText('Connected to Ankita', { exact: true }).waitFor();
  await waitConnected();
  const currentWorker = context.serviceWorkers().find(item => item.url().startsWith(`chrome-extension://${id}/`));
  assert.deepEqual(await currentWorker.evaluate(() => chrome.storage.local.get('pairedDesktop')), firstPair);
  assert.equal(posts, 2, 'desktop restart must not replay the published post');
  await context.close(); context = await launch();
  const restartedWorker = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
  const restoredPopup = await context.newPage(); await restoredPopup.goto(`chrome-extension://${id}/popup.html`);
  await restoredPopup.getByText('Connected to Ankita', { exact: true }).waitFor();
  assert.deepEqual(await restartedWorker.evaluate(() => chrome.storage.local.get('pairedDesktop')), firstPair);
  assert.equal(service.browserStatus().connected, true);
  assert.equal(posts, 2, 'browser restart must not replay the published post');
  await restoredPopup.getByRole('button', { name: 'Disconnect', exact: true }).click();
  await restoredPopup.getByText('Connection paused', { exact: true }).waitFor();
  assert.equal(service.browserStatus().paused, true);
  await service.pauseBrowser(false);
  await restartedWorker.evaluate(async () => { await chrome.alarms.create('ankita-browser-reconnect', { when: Date.now() + 100 }); });
  await restoredPopup.getByText('Connected to Ankita', { exact: true }).waitFor();
  assert.equal(service.browserStatus().connected, true);
  await service.revokeBrowser();
  try { await restoredPopup.getByText('Browser access removed. Pair with Ankita again.', { exact: true }).waitFor(); }
  catch (error) { console.log('REVOCATION_DIAGNOSTIC', await restoredPopup.evaluate(async () => ({ status: await chrome.runtime.sendMessage({ type: 'ankita-browser-status' }), text: document.querySelector('#connection').textContent }))); throw error; }
  assert.equal(await restoredPopup.getByRole('textbox', { name: 'ANKITA pairing code' }).isVisible(), true);
  assert.equal(service.browserStatus().paired, false);
  console.log('EXTENSION_LIVE_OK: one pairing; DOM post and Enter post exactly once each; screenshot; worker/desktop/browser restarts; cross-surface pause/resume; revoke recovery.');
});
