import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { chromium } from 'playwright';
const module = await import('../../desktop/browser-helper/page-operations.mjs').catch(() => null);

test('page operations fill and submit a real form and reject replaced or cross-job references', async t => {
  assert.ok(module, 'packaged extension page operations are implemented');
  const server = http.createServer((_req, res) => { res.setHeader('Content-Type', 'text/html'); res.end('<!doctype html><form><label>Name<input name="name"></label><label>Post<textarea name="post"></textarea></label><button>Publish</button><output></output></form><script>document.querySelector("form").onsubmit=e=>{e.preventDefault();document.querySelector("output").textContent=document.querySelector("textarea").value;window.posts=(window.posts||0)+1}</script>'); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ headless: true });
  t.after(async () => { await browser.close(); await new Promise(resolve => server.close(resolve)); });
  const page = await browser.newPage(); await page.goto(`http://127.0.0.1:${server.address().port}`);
  const call = request => page.evaluate(module.pageOperation, { ...request, scope: request.scope || 'job-a', stateKey: 'test-extension-state', limits: { controls: 100, text: 2000, name: 240 }, staleMessage: 'Fresh snapshot required' });
  const snapshot = await call({ action: 'snapshot' });
  const ref = name => snapshot.controls.find(c => c.name === name).ref;
  assert.equal((await call({ action: 'act', op: 'fill', ref: ref('Post'), documentId: snapshot.documentId, text: 'A real test post' })).error, undefined);
  await call({ action: 'act', op: 'type', ref: ref('Post'), documentId: snapshot.documentId, text: ' appended' });
  assert.equal(await page.locator('textarea').inputValue(), 'A real test post appended', 'type appends instead of deleting existing text');
  const invalid = await call({ scope: 'job-b', action: 'act', op: 'click', ref: ref('Publish'), documentId: snapshot.documentId });
  assert.match(invalid.error, /Fresh snapshot/);
  assert.equal(invalid.dispatched, false);
  await call({ action: 'act', op: 'click', ref: ref('Publish'), documentId: snapshot.documentId });
  assert.equal(await page.locator('output').textContent(), 'A real test post appended');
  assert.equal(await page.evaluate(() => window.posts), 1);
  const fresh = await call({ action: 'snapshot' });
  await page.evaluate(() => history.pushState({}, '', '/different-account'));
  const changed = await call({ action: 'act', op: 'click', ref: fresh.controls.find(c => c.name === 'Publish').ref, documentId: fresh.documentId, expectedUrl: page.url() });
  assert.match(changed.error, /Fresh snapshot/, 'a same-document route change invalidates old refs');
  assert.equal(changed.dispatched, false);
  await page.locator('button').evaluate(node => node.replaceWith(node.cloneNode(true)));
  const stale = await call({ action: 'act', op: 'click', ref: ref('Publish'), documentId: snapshot.documentId });
  assert.match(stale.error, /Fresh snapshot/);
  assert.equal(stale.dispatched, false);
  assert.equal(await page.evaluate(() => window.posts), 1);
  await page.route('http://insecure.test/**', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><title>Plain HTTP</title><button>Continue</button>' }));
  await page.goto('http://insecure.test/');
  assert.equal(await page.evaluate(() => typeof crypto.randomUUID), 'undefined', 'ordinary insecure HTTP lacks the secure-context UUID API');
  const insecure = await call({ action: 'snapshot' });
  assert.equal(Array.isArray(insecure.controls), true, 'ordinary HTTP can still produce safe opaque references');
});
